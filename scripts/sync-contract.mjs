#!/usr/bin/env node
// Generate contract/registry.snapshot.json from the CloudSee Drive public API endpoint seed.
// This is the offline source of truth the tool↔contract drift test diffs against
// (there is no static openapi.yaml; the live spec is generated at runtime).
// Reads the seed as TEXT and extracts endpoints by regex — it never executes the
// seed (which would require AWS) and never modifies any source file.
//
//   SEED_PATH=/abs/path/seed.js npm run sync:contract
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// SEED_PATH must point at the CloudSee Drive public API registry seed
// (seed-api-registry.js). The published package ships only the committed
// snapshot; set SEED_PATH to regenerate it, or keep using the committed one.
const SEED_PATH = process.env.SEED_PATH || resolve(root, "seed-api-registry.js");
const OUT_PATH = resolve(root, "contract", "registry.snapshot.json");

const SCOPES = {
  READ: ["drive:read"],
  DOWNLOAD: ["drive:read", "drive:download"],
  WRITE: ["drive:write"],
  DELETE: ["drive:delete"],
};

function extract(src) {
  const chunks = src.split(/\bep\(\{/).slice(1);
  const endpoints = [];
  for (const chunk of chunks) {
    const apiPath = /ApiPath:\s*'([^']+)'/.exec(chunk)?.[1];
    if (!apiPath) continue;
    const operationId = /OperationId:\s*'([^']+)'/.exec(chunk)?.[1] ?? null;
    const tag = /Tag:\s*'([^']+)'/.exec(chunk)?.[1] ?? null;
    const scopeName = /RequiredScopes:\s*([A-Z_]+)/.exec(chunk)?.[1];
    const target = /TargetHandlerPath:\s*'([^']*)'/.exec(chunk)?.[1] ?? null;
    const [method, path] = apiPath.split(/\s+/);
    endpoints.push({ method, path, operationId, tag, scopes: SCOPES[scopeName] ?? [], targetHandlerPath: target });
  }
  endpoints.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));
  return endpoints;
}

function main() {
  let src;
  try {
    src = readFileSync(SEED_PATH, "utf8");
  } catch {
    console.error(`Could not read the seed at:\n  ${SEED_PATH}`);
    console.error(`Set SEED_PATH to the CloudSee Drive public API registry seed (seed-api-registry.js), or keep using the committed snapshot.`);
    process.exit(1);
  }
  const endpoints = extract(src);
  if (endpoints.length === 0) {
    console.error("No endpoints extracted — the seed format may have changed. Aborting (not overwriting the snapshot).");
    process.exit(1);
  }
  const snapshot = {
    $comment:
      "Generated by scripts/sync-contract.mjs from the CloudSee Drive public API registry seed. " +
      "Data-plane (/v1/{proxy+}) endpoints only; the /v1/api-keys/* management plane is intentionally excluded. " +
      "Do not edit by hand — run `npm run sync:contract`.",
    plane: "data",
    source: "CloudSee Drive public API registry (seed-api-registry.js)",
    endpointCount: endpoints.length,
    endpoints,
  };
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
  console.log(`Wrote ${endpoints.length} data-plane endpoints to:\n  ${OUT_PATH}`);
}

main();
