#!/usr/bin/env node
// Generate contract/registry.snapshot.json from the CloudSee Drive public API endpoint seed.
// This is the offline source of truth the tool↔contract drift test diffs against
// (there is no static openapi.yaml; the live spec is generated at runtime).
// Reads the seed as TEXT and extracts endpoints by regex — it never executes the
// seed (which would require AWS) and never modifies any source file.
//
//   SEED_PATH=/abs/path/seed.js npm run sync:contract
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// SEED_PATH must point at the CloudSee Drive public API registry seed
// (seed-api-registry.js). The published package ships only the committed
// snapshot; set SEED_PATH to regenerate it, or keep using the committed one.
const SEED_PATH = process.env.SEED_PATH || resolve(root, "seed-api-registry.js");
const OUT_PATH = resolve(root, "contract", "registry.snapshot.json");

// The storage service's extension→MIME table. It decides which content type the
// pre-signed PUT is signed with, so the client must mirror it byte for byte (see
// src/tools/mime.ts). Defaults to the monorepo location; set MIME_SOURCE_PATH to
// override. Absent + not explicitly set ⇒ skipped, not an error, because the public
// repo ships only the committed snapshot.
const MIME_SOURCE_PATH =
  process.env.MIME_SOURCE_PATH || resolve(root, "../../storage/storage-api/lib/utils/ExtensionUtil.js");
const MIME_OUT_PATH = resolve(root, "contract", "mime.snapshot.json");

const SCOPES = {
  READ: ["drive:read"],
  DOWNLOAD: ["drive:read", "drive:download"],
  WRITE: ["drive:write"],
  DELETE: ["drive:delete"],
};

export function extract(src) {
  const chunks = src.split(/\bep\(\{/).slice(1);
  const endpoints = [];
  for (const chunk of chunks) {
    const apiPath = /ApiPath:\s*'([^']+)'/.exec(chunk)?.[1];
    if (!apiPath) continue;
    // A row the seed stages `Enabled: false` is written to the registry but kept out of
    // routing and out of the generated OpenAPI, so it is not part of the published surface
    // and must not enter the contract a tool is allowed to target (CSD-668 F-07).
    if (/\bEnabled:\s*false\b/.test(chunk)) continue;
    const operationId = /OperationId:\s*'([^']+)'/.exec(chunk)?.[1] ?? null;
    const tag = /Tag:\s*'([^']+)'/.exec(chunk)?.[1] ?? null;
    const scopeName = /RequiredScopes:\s*([A-Z_]+)/.exec(chunk)?.[1];
    const target = /TargetHandlerPath:\s*'([^']*)'/.exec(chunk)?.[1] ?? null;
    const [method, path] = apiPath.split(/\s+/);
    endpoints.push({ method, path, operationId, tag, scopes: SCOPES[scopeName] ?? [], targetHandlerPath: target });
  }
  endpoints.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));
  return endpoints;
}

/** Pull the `const mimeTypes = { … }` literal out of ExtensionUtil.js as TEXT. */
function extractMime(src) {
  const block = /const\s+mimeTypes\s*=\s*\{([\s\S]*?)\n\};/.exec(src)?.[1];
  if (!block) return null;
  const table = {};
  // Keys are bare identifiers or quoted (e.g. '7z'); values are single-quoted.
  const pair = /(?:^|,)\s*(?:\/\/[^\n]*\n\s*)*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_$]+))\s*:\s*'([^']*)'/g;
  for (let m = pair.exec(block); m; m = pair.exec(block)) {
    table[m[1] ?? m[2] ?? m[3]] = m[4];
  }
  return Object.keys(table).length ? table : null;
}

function syncMime() {
  const explicit = Boolean(process.env.MIME_SOURCE_PATH);
  let src;
  try {
    src = readFileSync(MIME_SOURCE_PATH, "utf8");
  } catch {
    if (!explicit) {
      console.log(`Skipped the MIME snapshot — no ExtensionUtil.js at:\n  ${MIME_SOURCE_PATH}`);
      console.log("  (set MIME_SOURCE_PATH to regenerate it; the committed snapshot stays authoritative)");
      return true;
    }
    console.error(`Could not read the MIME source at:\n  ${MIME_SOURCE_PATH}`);
    return false;
  }
  const mimeTypes = extractMime(src);
  if (!mimeTypes) {
    console.error("No mimeTypes table extracted — the ExtensionUtil format may have changed. Aborting (not overwriting the snapshot).");
    return false;
  }
  const sorted = Object.fromEntries(Object.keys(mimeTypes).sort().map((k) => [k, mimeTypes[k]]));
  const snapshot = {
    $comment:
      "Generated by scripts/sync-contract.mjs from the CloudSee storage service's lib/utils/ExtensionUtil.js. " +
      "This table decides the content type a pre-signed upload URL is signed with, so src/tools/mime.ts must match it " +
      "exactly or S3 rejects the PUT with 403 SignatureDoesNotMatch. Do not edit by hand.",
    source: "CloudSee storage-api (lib/utils/ExtensionUtil.js)",
    defaultContentType: "application/octet-stream",
    entryCount: Object.keys(sorted).length,
    mimeTypes: sorted,
  };
  mkdirSync(dirname(MIME_OUT_PATH), { recursive: true });
  writeFileSync(MIME_OUT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
  console.log(`Wrote ${snapshot.entryCount} MIME entries to:\n  ${MIME_OUT_PATH}`);
  return true;
}

function main() {
  const mimeOk = syncMime();
  let src;
  try {
    src = readFileSync(SEED_PATH, "utf8");
  } catch {
    console.error(`Could not read the seed at:\n  ${SEED_PATH}`);
    console.error(`Set SEED_PATH to the CloudSee Drive public API registry seed (seed-api-registry.js), or keep using the committed snapshot.`);
    process.exit(1);
  }
  const endpoints = extract(src);
  if (endpoints.length === 0) {
    console.error("No endpoints extracted — the seed format may have changed. Aborting (not overwriting the snapshot).");
    process.exit(1);
  }
  const snapshot = {
    $comment:
      "Generated by scripts/sync-contract.mjs from the CloudSee Drive public API registry seed. " +
      "Data-plane (/v1/{proxy+}) endpoints only; the /v1/api-keys/* management plane is intentionally excluded, " +
      "and rows the seed stages `Enabled: false` are excluded because they are kept out of routing and of the " +
      "generated OpenAPI. This snapshot is pinned to the PRODUCTION surface: the seeded set is stage-dependent, " +
      "so UAT publishes one endpoint fewer — `POST /storage/buckets` is retired there but still served on " +
      "production for the length of its deprecation window. " +
      "Do not edit by hand — run `npm run sync:contract`.",
    plane: "data",
    source: "CloudSee Drive public API registry (seed-api-registry.js)",
    endpointCount: endpoints.length,
    endpoints,
  };
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
  console.log(`Wrote ${endpoints.length} data-plane endpoints to:\n  ${OUT_PATH}`);
  if (!mimeOk) process.exit(1);
}

// Run only when invoked directly, so extract() can be unit-tested (test/contract/generator.test.ts)
// without writing a snapshot file (mirrors check-openapi-parity.js's `require.main === module`).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
